/*
 * Dump the test vectors embedded in c-fn-dsa's test_fndsa.c as plain-text
 * fixtures, so that the Rust port is checked against exactly the values the
 * reference checks itself against.
 *
 * Rather than parsing C initialisers (some of which are FPR(...) macro
 * expressions), this file #includes test_fndsa.c and lets the C compiler
 * evaluate every table. Its own main() is renamed out of the way.
 *
 * Built and run by scripts/c-fn-dsa/extract_vectors.sh; not part of the crate.
 *
 * Usage: dump_vectors <output-dir> <upstream-commit>
 */

#define main fndsa_upstream_test_main
#include "test_fndsa.c"
#undef main

static FILE *
open_out(const char *dir, const char *name, const char *commit,
	const char *what)
{
	char path[4096];
	snprintf(path, sizeof path, "%s/%s", dir, name);
	FILE *f = fopen(path, "w");
	if (f == NULL) {
		perror(path);
		exit(EXIT_FAILURE);
	}
	fprintf(f, "# Generated by scripts/c-fn-dsa/extract_vectors.sh"
		" -- do not edit.\n");
	fprintf(f, "# Source: github.com/pornin/c-fn-dsa @ %s,"
		" test_fndsa.c\n", commit);
	fprintf(f, "# %s\n", what);
	return f;
}

static void
put_hex(FILE *f, const uint8_t *buf, size_t len)
{
	for (size_t i = 0; i < len; i ++) {
		fprintf(f, "%02x", buf[i]);
	}
}

/* NULL-terminated array of hex strings, one per line. */
static void
dump_str_list(const char *dir, const char *name, const char *commit,
	const char *what, const char *const *list)
{
	FILE *f = open_out(dir, name, commit, what);
	for (size_t i = 0; list[i] != NULL; i ++) {
		fprintf(f, "%s\n", list[i]);
	}
	fclose(f);
}

static void
dump_bytes(const char *dir, const char *name, const char *commit,
	const char *what, const uint8_t *buf, size_t len)
{
	FILE *f = open_out(dir, name, commit, what);
	put_hex(f, buf, len);
	fprintf(f, "\n");
	fclose(f);
}

int
main(int argc, char *argv[])
{
	if (argc != 3) {
		fprintf(stderr, "usage: dump_vectors <out-dir> <commit>\n");
		return EXIT_FAILURE;
	}
	const char *dir = argv[1];
	const char *c = argv[2];
	FILE *f;

	/* SHA3: pairs (input, output); output length selects the variant.
	   Written as "input:output" so an empty input stays visible. */
	f = open_out(dir, "sha3.txt", c,
		"SHA3-{224,256,384,512}: <msg hex>:<digest hex>;"
		" digest length selects the variant");
	for (size_t i = 0; KAT_SHA3[i] != NULL; i += 2) {
		fprintf(f, "%s:%s\n", KAT_SHA3[i], KAT_SHA3[i + 1]);
	}
	fclose(f);

	/* Sampler: seed, expected nonce, then (mu, 1/sigma, output). The
	   two floating-point inputs are written as their IEEE-754 binary64
	   bit patterns, which is exactly how the reference stores them. */
	f = open_out(dir, "sampler_512.txt", c,
		"sampler_next() at logn=9. SHAKE256(seed) -> 40-byte nonce,"
		" then the same SHAKE state feeds the sampler.");
	fprintf(f, "seed=");
	put_hex(f, KAT_SAMPLER_512_SEED, sizeof KAT_SAMPLER_512_SEED);
	fprintf(f, "\nnonce=");
	put_hex(f, KAT_SAMPLER_512_NONCE, sizeof KAT_SAMPLER_512_NONCE);
	fprintf(f, "\n# <mu bits hex> <inv_sigma bits hex> <output>\n");
	size_t klen = (sizeof KAT_SAMPLER_512_MU) / sizeof(fpr);
	if (klen != (sizeof KAT_SAMPLER_512_INVSIGMA) / sizeof(fpr)
		|| klen != (sizeof KAT_SAMPLER_512_OUT) / sizeof(int16_t))
	{
		fprintf(stderr, "sampler table length mismatch\n");
		return EXIT_FAILURE;
	}
	for (size_t i = 0; i < klen; i ++) {
		fprintf(f, "%016llx %016llx %d\n",
			(unsigned long long)KAT_SAMPLER_512_MU[i],
			(unsigned long long)KAT_SAMPLER_512_INVSIGMA[i],
			(int)KAT_SAMPLER_512_OUT[i]);
	}
	fclose(f);

	/* Keygen reference vectors: entry i uses seed "test<i>" (ASCII,
	   no terminator); value is SHA-256(f || g || F || G) as int8. */
	dump_str_list(dir, "keygen_256.txt", c,
		"logn=8, seed=\"test<i>\": SHA-256(f||g||F||G)", KAT_KG256);
	dump_str_list(dir, "keygen_512.txt", c,
		"logn=9, seed=\"test<i>\": SHA-256(f||g||F||G)", KAT_KG512);
	dump_str_list(dir, "keygen_1024.txt", c,
		"logn=10, seed=\"test<i>\": SHA-256(f||g||F||G)", KAT_KG1024);

	/* Verify vectors: ctx "context", raw message "message". */
	dump_bytes(dir, "verify_512_vk.hex", c,
		"verifying key; signs ctx=\"context\", raw msg=\"message\"",
		KAT_512_VK, sizeof KAT_512_VK);
	dump_bytes(dir, "verify_512_sig.hex", c,
		"signature over ctx=\"context\", raw msg=\"message\"",
		KAT_512_SIG, sizeof KAT_512_SIG);
	dump_bytes(dir, "verify_1024_vk.hex", c,
		"verifying key; signs ctx=\"context\", raw msg=\"message\"",
		KAT_1024_VK, sizeof KAT_1024_VK);
	dump_bytes(dir, "verify_1024_sig.hex", c,
		"signature over ctx=\"context\", raw msg=\"message\"",
		KAT_1024_SIG, sizeof KAT_1024_SIG);

	/* End-to-end KAT. See the comment above KAT_4 in test_fndsa.c. */
	static const struct {
		unsigned logn;
		const char *const *kat;
	} KATS[] = {
		{ 2, KAT_4 }, { 3, KAT_8 }, { 4, KAT_16 }, { 5, KAT_32 },
		{ 6, KAT_64 }, { 7, KAT_128 }, { 8, KAT_256 },
		{ 9, KAT_512 }, { 10, KAT_1024 }
	};
	for (size_t i = 0; i < sizeof KATS / sizeof KATS[0]; i ++) {
		char name[64];
		snprintf(name, sizeof name, "kat_%u.txt", 1u << KATS[i].logn);
		dump_str_list(dir, name, c,
			"j-th line: seed=logn||j (1+4 bytes LE);"
			" SHAKE256(seed) -> seed_kgen(32), seed_sign(40);"
			" ctx=\"domain\", msg=\"message\" (raw if j even,"
			" SHA3-256 pre-hashed if j odd);"
			" value = SHA3-256(sk||vk||sig)",
			KATS[i].kat);
	}

	return 0;
}
