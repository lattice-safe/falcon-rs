#!/usr/bin/env bash
# Regenerate tests/fixtures/c-fn-dsa/ from the pinned c-fn-dsa test_fndsa.c.
#
# The tables are dumped by compiling dump_vectors.c, which #includes the
# reference's test file, so every value -- including FPR(...) macro
# constants -- is evaluated by the C compiler rather than re-parsed here.
# The three SHAKE256 vectors are inline string arguments rather than tables,
# so they are pulled out of the source text instead.
#
# Usage: scripts/c-fn-dsa/extract_vectors.sh [checkout-dir]
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$HERE/../.." && pwd)"
commit=$(sed -n 's/^commit=//p' "$HERE/UPSTREAM")
SRC="$("$HERE/fetch.sh" "${1:-}" | tail -n 1)"
OUT="$REPO_ROOT/tests/fixtures/c-fn-dsa"

BUILD="$(mktemp -d)"
trap 'rm -rf "$BUILD"' EXIT

CC="${CC:-cc}"
"$CC" -O1 -w -I"$SRC" -o "$BUILD/dump_vectors" "$HERE/dump_vectors.c" \
    "$SRC"/codec.c "$SRC"/mq.c "$SRC"/sha3.c "$SRC"/sysrng.c "$SRC"/util.c \
    "$SRC"/kgen*.c "$SRC"/sign*.c "$SRC"/vrfy.c

rm -rf "$OUT"
mkdir -p "$OUT"
"$BUILD/dump_vectors" "$OUT" "$commit"

# SHAKE256 vectors: inner_test_SHAKE256("<in>", "<out>", tmp, tlen);
python3 -I - "$SRC/test_fndsa.c" "$OUT/shake256.txt" "$commit" <<'PY'
import re, sys
src, out, commit = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src).read()
body = text[text.index("test_SHAKE256(void)"):]
body = body[:body.index("xfree(tmp);")]
pairs = re.findall(r'inner_test_SHAKE256\(\s*"([0-9a-f]*)",\s*"([0-9a-f]+)",', body)
if len(pairs) != 3:
    sys.exit(f"expected 3 SHAKE256 vectors, found {len(pairs)}")
with open(out, "w") as f:
    f.write("# Generated by scripts/c-fn-dsa/extract_vectors.sh -- do not edit.\n")
    f.write(f"# Source: github.com/pornin/c-fn-dsa @ {commit}, test_fndsa.c\n")
    f.write("# SHAKE256: <msg hex>:<output hex>\n")
    for i, o in pairs:
        f.write(f"{i}:{o}\n")
PY

echo "Wrote $(ls "$OUT" | wc -l | tr -d ' ') fixture files to tests/fixtures/c-fn-dsa/"
