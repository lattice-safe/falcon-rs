"""Generate tests/fixtures/c-fn-dsa/api_vectors.txt from the C reference.

Each case is keygen from a seed, then a seeded signature in one
domain-separation mode, computed by c-fn-dsa through its public API
(api_vector.c). Pre-hash digests come from Python's hashlib. The Rust
high-level API must reproduce every key and signature byte for byte.

Usage (from extract_vectors.sh): python3 -I gen_api_vectors.py <api_vector binary> <out file> <commit>
"""
import hashlib
import subprocess
import sys

binary, out_path, commit = sys.argv[1], sys.argv[2], sys.argv[3]

MSG = b"FIPS 206 FN-DSA Known Answer Test"
CTX = b"fips206-ctx-v1"
SIGN_SEED = b"fips206-kat-sign-seed"

DIGEST = {
    "raw": lambda m: m,
    "extmu": lambda m: m,
    "sha256": lambda m: hashlib.sha256(m).digest(),
    "sha512": lambda m: hashlib.sha512(m).digest(),
    "sha3_256": lambda m: hashlib.sha3_256(m).digest(),
    "sha3_512": lambda m: hashlib.sha3_512(m).digest(),
}

CASES = []
for logn in (9, 10):
    kseed = b"fips206-kat-key-seed-%d" % (1 << logn)
    for mode in ("raw", "sha256", "sha512", "sha3_256", "sha3_512", "extmu"):
        for ctx in (b"", CTX):
            CASES.append((logn, kseed, ctx, mode))
# An empty message and a long one, raw mode.
CASES.append((9, b"fips206-kat-key-seed-512", b"", "raw-empty"))
CASES.append((9, b"fips206-kat-key-seed-512", CTX, "raw-long"))

with open(out_path, "w") as f:
    f.write("# Generated by scripts/c-fn-dsa/extract_vectors.sh -- do not edit.\n")
    f.write(f"# Source: github.com/pornin/c-fn-dsa @ {commit}, fndsa.h API via api_vector.c\n")
    f.write("# logn|key_seed|ctx|mode|msg|sign_seed|sk|vk|mu|sig (hex except logn, mode)\n")
    for logn, kseed, ctx, mode in CASES:
        msg = MSG
        if mode == "raw-empty":
            mode, msg = "raw", b""
        elif mode == "raw-long":
            mode, msg = "raw", bytes(range(256)) * 40
        hv = DIGEST[mode](msg)
        res = subprocess.run(
            [binary, str(logn), kseed.hex(), ctx.hex(), mode, hv.hex(), SIGN_SEED.hex()],
            check=True, capture_output=True, text=True,
        ).stdout.split()
        sk, vk, mu, sig = res
        f.write("|".join([str(logn), kseed.hex(), ctx.hex(), mode, msg.hex(),
                          SIGN_SEED.hex(), sk, vk, mu, sig]) + "\n")
print(f"wrote {len(CASES)} API vectors")
